/** Encode RGBA8 pixels to a DDS file (BC1, BC3, BC7). */
export async function encodeDds(
  pixels: Uint8Array,
  width: number,
  height: number,
  fmt: number,
  mipLevels: number = 1,
  headerMode: number = DdsHeaderMode.AUTO,
): Promise<Uint8Array> {
  const m = await getPixelOps();
  const outSize = m._pixelops_dds_get_encoded_size(
    width,
    height,
    fmt,
    mipLevels,
    headerMode,
  );
  if (outSize <= 0) throw new Error(ddsErrorFromCode(outSize));
  const srcPtr = m._malloc(pixels.byteLength);
  const outPtr = m._malloc(outSize);
  try {
    m.HEAPU8.set(pixels, srcPtr);
    const err = m._pixelops_dds_encode(
      srcPtr,
      width,
      height,
      fmt,
      mipLevels,
      headerMode,
      outPtr,
      outSize,
    );
    if (err !== 0) throw new Error(ddsErrorFromCode(err));
    const out = new Uint8Array(outSize);
    out.set(m.HEAPU8.subarray(outPtr, outPtr + outSize));
    return out;
  } finally {
    m._free(srcPtr);
    m._free(outPtr);
  }
}

/** Encode RGBA float32 pixels to a DDS file (BC6H UF16 or raw RGBA32F). */
export async function encodeDdsF32(
  pixels: Float32Array,
  width: number,
  height: number,
  fmt: number,
  mipLevels: number = 1,
): Promise<Uint8Array> {
  const m = await getPixelOps();
  const outSize = m._pixelops_dds_get_encoded_size(
    width,
    height,
    fmt,
    mipLevels,
    DdsHeaderMode.DX10,
  );
  if (outSize <= 0) throw new Error(ddsErrorFromCode(outSize));
  const srcPtr = m._malloc(pixels.byteLength);
  const outPtr = m._malloc(outSize);
  try {
    new Float32Array(
      m.HEAPU8.buffer,
      m.HEAPU8.byteOffset + srcPtr,
      pixels.length,
    ).set(pixels);
    const err = m._pixelops_dds_encode_f32(
      srcPtr,
      width,
      height,
      fmt,
      mipLevels,
      DdsHeaderMode.DX10,
      outPtr,
      outSize,
    );
    if (err !== 0) throw new Error(ddsErrorFromCode(err));
    const out = new Uint8Array(outSize);
    // Re-read HEAPU8 in case WASM memory grew
    out.set(m.HEAPU8.subarray(outPtr, outPtr + outSize));
    return out;
  } finally {
    m._free(srcPtr);
    m._free(outPtr);
  }
}

/** Maximum mip levels such that the smallest dimension is >= minDim. */
export async function maxDdsMipLevels(
  width: number,
  height: number,
  minDim: number,
): Promise<number> {
  const m = await getPixelOps();
  return m._pixelops_dds_max_mip_levels(width, height, minDim);
}

