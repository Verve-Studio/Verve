/**
 * Content-aware inpainting (PatchMatch).
 *
 * @param pixels   RGBA flat canvas composite, width × height × 4 bytes.
 * @param width    Canvas width in pixels.
 * @param height   Canvas height in pixels.
 * @param mask     Single-channel fill mask from activeScope().selection.mask,
 *                 width × height bytes (255 = fill region, 0 = source region).
 * @param sourceMask  Optional source-eligibility mask (1 = eligible, 0 = excluded).
 *                    Pass undefined for unconstrained (sample entire image).
 * @returns        RGBA output buffer, same dimensions as pixels.
 *                 Pixels outside the mask are unchanged copies of the input.
 */
export async function inpaintRegion(
  pixels: Uint8Array,
  width: number,
  height: number,
  mask: Uint8Array,
  sourceMask?: Uint8Array,
): Promise<Uint8Array> {
  assertBytes("inpaintRegion", pixels);

  // Run on a crop around the fill instead of the whole canvas. Level 0 of
  // the PatchMatch pyramid copies every pixel plus ~20 bytes/pixel of
  // bookkeeping, so filling a small area of an 8K document used to grow the
  // WASM heap by >1.3 GB (and the heap never shrinks).
  //  - With a source mask, patches can only come from it, so cropping to
  //    fill ∪ source gives exactly the same result.
  //  - Without one, keep a generous margin of surrounding context.
  const fill = maskBounds(mask, width, height);
  if (!fill) return pixels.slice();
  let crop: MaskBounds;
  if (sourceMask !== undefined) {
    const src = maskBounds(sourceMask, width, height);
    crop = src ? unionBounds(fill, src) : fill;
  } else {
    const margin = Math.max(256, 2 * Math.max(fill.x1 - fill.x0, fill.y1 - fill.y0));
    crop = {
      x0: Math.max(0, fill.x0 - margin),
      y0: Math.max(0, fill.y0 - margin),
      x1: Math.min(width, fill.x1 + margin),
      y1: Math.min(height, fill.y1 + margin),
    };
  }
  if (crop.x0 > 0 || crop.y0 > 0 || crop.x1 < width || crop.y1 < height) {
    const cw = crop.x1 - crop.x0;
    const ch = crop.y1 - crop.y0;
    const cropped = await inpaintRegion(
      cropRegion(pixels, width, crop, 4),
      cw,
      ch,
      cropRegion(mask, width, crop, 1),
      sourceMask !== undefined ? cropRegion(sourceMask, width, crop, 1) : undefined,
    );
    const out = pixels.slice();
    for (let y = 0; y < ch; y++) {
      out.set(
        cropped.subarray(y * cw * 4, (y + 1) * cw * 4),
        ((crop.y0 + y) * width + crop.x0) * 4,
      );
    }
    return out;
  }

  const m = await getPixelOps();
  const PATCH_SIZE = 4; // → 9×9 patches
  const byteLen = pixels.byteLength; // width * height * 4

  const pixelsPtr = m._malloc(byteLen);
  const maskPtr = m._malloc(mask.byteLength);
  const outPtr = m._malloc(byteLen);
  let sourceMaskPtr = 0;
  try {
    m.HEAPU8.set(pixels, pixelsPtr);
    m.HEAPU8.set(mask, maskPtr);
    if (sourceMask !== undefined) {
      sourceMaskPtr = m._malloc(sourceMask.byteLength);
      m.HEAPU8.set(sourceMask, sourceMaskPtr);
    }
    m._pixelops_inpaint(
      pixelsPtr,
      width,
      height,
      maskPtr,
      PATCH_SIZE,
      sourceMaskPtr,
      outPtr,
    );
    // Re-read HEAPU8 in case WASM memory grew during the call
    return m.HEAPU8.slice(outPtr, outPtr + byteLen);
  } finally {
    m._free(pixelsPtr);
    m._free(maskPtr);
    if (sourceMaskPtr !== 0) m._free(sourceMaskPtr);
    m._free(outPtr);
  }
}

interface MaskBounds {
  x0: number;
  y0: number;
  x1: number;
  y1: number;
}

/** Bounding box (exclusive right/bottom) of the non-zero pixels of a
 *  1-byte-per-pixel mask, or null when it is empty. */
function maskBounds(mask: Uint8Array, w: number, h: number): MaskBounds | null {
  let x0 = w;
  let y0 = h;
  let x1 = -1;
  let y1 = -1;
  for (let y = 0; y < h; y++) {
    const row = y * w;
    for (let x = 0; x < w; x++) {
      if (mask[row + x] === 0) continue;
      if (x < x0) x0 = x;
      if (x > x1) x1 = x;
      if (y < y0) y0 = y;
      if (y > y1) y1 = y;
    }
  }
  return x1 < 0 ? null : { x0, y0, x1: x1 + 1, y1: y1 + 1 };
}

function unionBounds(a: MaskBounds, b: MaskBounds): MaskBounds {
  return {
    x0: Math.min(a.x0, b.x0),
    y0: Math.min(a.y0, b.y0),
    x1: Math.max(a.x1, b.x1),
    y1: Math.max(a.y1, b.y1),
  };
}

/** Copy a rectangle out of a row-major buffer with `bpp` bytes per pixel. */
function cropRegion(
  src: Uint8Array,
  srcW: number,
  r: MaskBounds,
  bpp: number,
): Uint8Array {
  const cw = r.x1 - r.x0;
  const out = new Uint8Array(cw * (r.y1 - r.y0) * bpp);
  for (let y = r.y0; y < r.y1; y++) {
    const from = (y * srcW + r.x0) * bpp;
    out.set(src.subarray(from, from + cw * bpp), (y - r.y0) * cw * bpp);
  }
  return out;
}

/**
 * GrabCut segmentation (Rother et al. 2004).
 *
 * @param pixels    RGBA image, width×height×4 bytes.
 * @param width     Image width.
 * @param height    Image height.
 * @param trimap    Per-pixel trimap: 0=BG, 128=unknown, 255=FG. width×height bytes.
 * @param iterations EM iterations (3 is typically sufficient).
 * @param k         GMM components per class (5 recommended).
 * @returns         Binary alpha mask (0 or 255), width×height bytes.
 */
export async function grabCut(
  pixels: Uint8Array,
  width: number,
  height: number,
  trimap: Uint8Array,
  iterations = 3,
  k = 5,
): Promise<Uint8Array> {
  const m = await getPixelOps();
  const n = width * height;

  const rgbaPtr = m._malloc(pixels.byteLength);
  const trimapPtr = m._malloc(n);
  const alphaPtr = m._malloc(n);
  try {
    m.HEAPU8.set(pixels, rgbaPtr);
    m.HEAPU8.set(trimap, trimapPtr);
    m._pixelops_grabcut(
      rgbaPtr,
      width,
      height,
      trimapPtr,
      alphaPtr,
      iterations,
      k,
    );
    // Re-read HEAPU8 in case WASM memory grew
    return m.HEAPU8.slice(alphaPtr, alphaPtr + n);
  } finally {
    m._free(rgbaPtr);
    m._free(trimapPtr);
    m._free(alphaPtr);
  }
}

